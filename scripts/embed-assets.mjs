// Embed contracts and packs into testkit-core so the single-file bundle needs no files beside it.
// Run with: pnpm embed. A test fails if the embedded copy drifts from contracts/ and packs/.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
const contracts = Object.fromEntries(readdirSync("contracts").filter((f) => f.endsWith(".schema.json")).sort().map((f) => [f, readFileSync(`contracts/${f}`, "utf8")]));
const packs = Object.fromEntries(readdirSync("packs").filter((f) => /\.(ya?ml|json)$/.test(f)).sort().map((f) => [f, readFileSync(`packs/${f}`, "utf8")]));
writeFileSync("packages/testkit-core/src/embedded.ts",
  "// GENERATED by scripts/embed-assets.mjs from contracts/ and packs/. Do not edit; run `pnpm embed`.\n" +
  `export const EMBEDDED_CONTRACTS: Record<string, string> = ${JSON.stringify(contracts, null, 0)};\n` +
  `export const EMBEDDED_PACKS: Record<string, string> = ${JSON.stringify(packs, null, 0)};\n`);
console.log(`embedded ${Object.keys(contracts).length} contracts and ${Object.keys(packs).length} packs`);
